import { mkdir, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format } from "prettier";
import { createDocument } from "../../apps/api/dist/openapi.js";

export const contractFiles = [
  "contracts/openapi.json",
  "apps/web/src/shared/api/generated/schema.d.ts",
];

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonical(value[key])]),
    );
  return value;
}

export async function generateContract(outputRoot) {
  const document = canonical(await createDocument());
  if (document.openapi !== "3.0.3") throw new Error("Expected OpenAPI 3.0.3");
  const types = astToString(await openapiTS(document));
  const contents = [
    await format(JSON.stringify(document), { parser: "json" }),
    await format(
      "// Generated by product:contract:generate. Do not edit.\n" + types,
      { parser: "typescript" },
    ),
  ];
  for (const [index, file] of contractFiles.entries()) {
    const target = resolve(outputRoot, file);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, contents[index]);
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateContract(resolve("."));
  console.log("Generated OpenAPI 3.0.3 and web types from Nest.");
}
